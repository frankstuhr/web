/* Glyph einer Variante holen; was die Variante nicht kennt, kommt aus A00. */
function glyphIn(fontKey, ch) {
  const f = FONTS[fontKey];
  if (f && f.glyphs[ch]) return f.glyphs[ch];
  return glyphFor(ch);
}

/* Stellt die Variante dieses Zeichen selbst? (für die Zeichensatz-Übersicht) */
function isOwnGlyph(fontKey, ch) {
  const f = FONTS[fontKey];
  return !!(f && f.glyphs[ch]);
}
